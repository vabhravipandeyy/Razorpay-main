class ReportingService:
    """
    Formal Report Generation & Data Export Engine (Phase 8).
    Produces audit-verifiable JSON dockets, printable HTML reports, and secure CSV datasets.
    """

    @classmethod
    def generate_executive_report(
        cls,
        db: Session,
        days: int = 30,
        user: Optional[User] = None,
        ip_address: Optional[str] = None
    ) -> Dict[str, Any]:
        overview = AnalyticsService.get_overview_kpis(db, days)
        distribution = AnalyticsService.get_risk_distribution(db)
        signals = AnalyticsService.get_risk_signals_frequency(db)
        routes = AnalyticsService.get_suspicious_routes_analytics(db, limit=5)
        regions = AnalyticsService.get_regional_risk_analytics(db)[:5]

        report = {
            "report_type": "EXECUTIVE_RISK_SUMMARY",
            "title": "GST Risk Management Executive Intelligence Report",
            "reporting_period_days": days,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "generated_by": user.full_name or user.username if user else "System Administrator",
            "overview_kpis": overview,
            "risk_distribution": distribution,
            "top_risk_signals": signals,
            "top_suspicious_corridors": routes,
            "top_risk_regions": regions,
            "disclaimer": DISCLAIMER,
        }

        # Log Report Generation
        if user:
            meta = ReportMetadata(
                report_type="EXECUTIVE_REPORT",
                title=f"Executive Risk Report ({days} Days)",
                generated_by=user.id,
                parameters_json=json.dumps({"days": days})
            )
            db.add(meta)
            db.commit()

            AuditService.log_event(
                db=db,
                action="REPORT_GENERATED",
                user_id=user.id,
                username=user.username,
                resource_type="REPORT",
                resource_id="EXECUTIVE_SUMMARY",
                status="SUCCESS",
                ip_address=ip_address,
                metadata={"report_type": "EXECUTIVE_REPORT"}
            )

        return report

